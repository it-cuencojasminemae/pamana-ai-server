'use strict';
// All activation mutations are confined to session-local TEMP tables that
// shadow the existing schema. Never apply synthetic verification to public data.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { connect } = require('./seed-phase5b-transfer-research');
const { activate, rollback, transportDigest, TABLES } = require('./activate-san-fernando-expansion');
const manifest = require('./data/san-fernando-expansion.json');
async function main() {
  const client = await connect();
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'pamana-csf-test-'));
  const receiptFile = path.join(folder, 'TEST-ONLY-receipt.json');
  let publicBefore;
  try {
    publicBefore = await transportDigest(client);
    for (const table of TABLES) {
      await client.query(`create temporary table ${table} (like public.${table} including constraints) on commit preserve rows`);
      await client.query(`alter table pg_temp.${table} alter column id add generated by default as identity`);
      await client.query(`insert into pg_temp.${table} select * from public.${table}`);
      await client.query(`select setval(pg_get_serial_sequence('pg_temp.${table}','id'),coalesce((select max(id) from pg_temp.${table}),0)+1,false)`);
      const record = (await client.query("select relpersistence from pg_class where oid=to_regclass($1)", [table])).rows[0];
      assert.equal(record.relpersistence, 't', 'A mutation target did not resolve to a temporary table');
    }
    const data = structuredClone(manifest), before = await transportDigest(client);
    const review = { reviewedBy: 'TEST ONLY', sourceReference: 'SYNTHETIC TEMP SCHEMA ONLY', verifiedAt: '2026-10-07T00:00:00Z' };
    data.status = 'VERIFIED'; data.review = review;
    // Synthetic, separate curb points near the reported corridor. No real-world assertion.
    for (const [index, n] of data.nodes.entries()) {
      n.latitude ??= 15.047 - index * 0.001;
      n.longitude ??= 120.692 - index * 0.0002;
      n.verification = review;
    }
    const mexico = (await client.query('select * from transport_nodes where node_code=$1', ['RCH-MEXICO-BAYAN-STA-MONICA-TRANSFER'])).rows[0];
    const nodes = new Map(data.nodes.map(n => [n.node_code, n])); nodes.set(mexico.node_code, mexico);
    for (const v of data.variants) {
      v.geometry_source = 'MANUAL_VERIFIED';
      v.geometry_geojson = { type: 'LineString', coordinates: v.stops.map(code => { const n = nodes.get(code); return [Number(n.longitude), Number(n.latitude)]; }) };
      v.corridorVerification = { ...review, stopOrderConfirmed: true, serviceTerminusConfirmed: true, jeepCorridorConfirmed: true };
    }
    data.connections[0].status = 'VERIFIED'; data.connections[0].verification = { ...review, pedestrianConnectionConfirmed: true };
    const dryRun = await activate(client, data, { receiptFile });
    assert.equal(dryRun.changed, true); assert.equal(await transportDigest(client), before); assert.equal(fs.existsSync(receiptFile), false);
    console.log('ok - activation dry run rolls back all temporary insertions and permission changes');
    const applied = await activate(client, data, { apply: true, receiptFile });
    assert.equal(applied.changedPermissions.length, 2); assert.equal(applied.inserted.filter(r => r.table === 'route_variants').length, 3);
    const repeated = await activate(client, data, { apply: true, receiptFile });
    assert.equal(repeated.changed, false); assert.equal(repeated.afterDigest, applied.afterDigest);
    console.log('ok - verified activation is idempotent and changes only its two existing transfer flags');
    const drifted = structuredClone(data); drifted.nodes[0].latitude += 0.001;
    await assert.rejects(activate(client, drifted, { apply: true, receiptFile }), /drift/i);
    assert.equal(await transportDigest(client), applied.afterDigest);
    const dryRollback = await rollback(client, applied); assert.equal(dryRollback.rolledBack, false); assert.equal(await transportDigest(client), applied.afterDigest);
    await rollback(client, applied, { apply: true }); assert.equal(await transportDigest(client), before);
    console.log('ok - drift is rejected atomically and receipt rollback restores every original transport row');
    for (const table of [...TABLES].reverse()) await client.query(`drop table pg_temp.${table}`);
    assert.equal(await transportDigest(client), publicBefore);
    console.log('ok - live public transport tables are unchanged by all activation and rollback tests');
  } finally {
    await client.end();
    if (fs.existsSync(receiptFile)) fs.unlinkSync(receiptFile);
    fs.rmdirSync(folder);
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
